import re

from invoicez.paths import Paths

# Top-level fields read without parsing the YAML, to answer completion quickly.
_FIELD_RE = re.compile(
    r"^(document_number|company|date|cancels|quote):[ \t]*['\"]?([^'\"\n#]*)",
    re.MULTILINE,
)

# The commands whose DOCUMENT argument takes an invoice number.
_DOCUMENT_COMMANDS = ("run", "send", "cancel")

_ZSH_FUNCTION = """
_{prog}_documents() {{
  local -a numbers
  local ret=1
  numbers=(${{(f)"$({prog} complete-documents 2>/dev/null)"}})
  _describe -t numbers 'invoice number' numbers && ret=0
  _files -g '*.(yml|yaml)' && ret=0
  return ret
}}
"""


def complete_documents() -> None:
    """Print the invoice numbers with what they bill, one per line, for completion."""
    lines = []
    for path in Paths().git_dir.glob("**/*.yml"):
        fields = dict(_FIELD_RE.findall(path.read_text(encoding="utf8")))
        number = fields.get("document_number", "").strip()
        if not number or fields.get("quote", "").strip().casefold() in {"true", "yes"}:
            continue
        if "cancels" in fields:
            what = f"credit note for {fields['cancels'].strip()}"
        else:
            what = fields.get("company", "").strip()
        lines.append(f"{number}:{what} {fields.get('date', '').strip()}".rstrip())
    print("\n".join(sorted(lines, reverse=True)))


def add_document_completion(script: str, prog: str) -> str:
    """Make a zsh completion script offer invoice numbers for DOCUMENT arguments.

    Args:
        script: zsh completion script generated by cyclopts.
        prog: Name of the program.

    Returns:
        The script, with the DOCUMENT argument of run, send and cancel completed by
        a function calling the complete-documents command.
    """
    action = f"_{prog}_documents"

    def complete_block(match: re.Match[str]) -> str:
        block = re.sub(r"('1:[^']*)'", rf"\1:{action}'", match[0], count=1)
        return re.sub(r"(--document\[[^']*\]:document)'", rf"\1:{action}'", block)

    commands = "|".join(_DOCUMENT_COMMANDS)
    script = re.sub(
        rf"^\s+({commands})\)\n.*?^\s+;;$",
        complete_block,
        script,
        flags=re.MULTILINE | re.DOTALL,
    )
    header, _, body = script.partition("\n")
    return f"{header}\n{_ZSH_FUNCTION.format(prog=prog)}{body}"
