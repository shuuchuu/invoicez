from pathlib import Path
from pprint import pprint

from invoicez.superpdp.invoices import send_invoice, validate_invoice


def send(path: Path, *, validate: bool = True, dry_run: bool = True) -> None:
    """Send a Factur-X invoice via SuperPDP.

    Args:
        path: Path to a facture-X file (PDF/A-3) such as one generated by invoicez run.
        validate: Validate the generated XML against SuperPDP before sending.
        dry_run: Build (and optionally validate) the invoice without sending it.
    """
    pdf_bytes = path.read_bytes()

    if validate:
        result = validate_invoice(pdf_bytes)
        if result["data"][0]["is_valid"]:
            print("Invoice validation succeeded")
        else:
            print("Invoice validation failed")
            pprint(result["data"][0]["subreports"])

    if dry_run:
        print("Dry run: invoice not sent. Pass --no-dry-run to actually send it.")
        return

    result = send_invoice(pdf_bytes)
    match result["http_status_code"]:
        case 200:
            print(f"Invoice sent: {result}")
        case 400:
            print(f"Invoice NOT sent due to bad parameters: {result['message']}")
        case 500:
            print(f"Invoice NOT sent due to server error: {result['message']}")
